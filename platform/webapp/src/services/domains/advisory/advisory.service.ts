    const orgId = getEffectiveOrgId();
    if (!orgId) {
      throw new Error("Organization ID is required");
    }

    const url = `/orgs/${orgId}//v1/advisory/remediation-proposals` + (params ? `?${new URLSearchParams(params).toString()}` : '');

